"""Score lulus.ai on synthetic filings with seeded, labelled errors.

    python tools/benchmark.py

Writes results/benchmark.md and results/benchmark.json. The filings are
generated by tools/make_samples.py, so these numbers show the prototype
works as designed; they are NOT a measure of real-world accuracy.
"""

from __future__ import annotations

import json
import statistics
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from lulus.check import precheck  # noqa: E402
from tools.make_samples import KINDS, make_set  # noqa: E402

NUMERIC_KINDS = {"TRANSPOSITION", "DIGIT", "SIGN", "SCALE"}


def score(sample_dir: Path) -> dict:
    labels = make_set(sample_dir)
    per_kind = defaultdict(lambda: {"n": 0, "detected": 0, "exact_field": 0, "field_flagged": 0, "cause": 0,
                                    "fix": 0})
    clean_issues, extra_issues, times, network = 0, 0, [], 0
    total_expl, actionable = 0, 0

    for lab in labels:
        res = precheck(sample_dir / lab["file"])
        times.append(res.seconds)
        network += res.network_attempts
        total_expl += len(res.explanations)
        actionable += sum(1 for x in res.explanations if x.is_actionable)
        kind = lab["kind"]
        if kind == "CLEAN":
            clean_issues += len(res.explanations)
            continue
        k = per_kind[kind]
        k["n"] += 1
        errors = [x for x in res.explanations if x.severity == "error"]
        if errors:
            k["detected"] += 1
        if kind == "MISSING_SECTION":
            hit = [x for x in errors if "REQ-S01" in x.rule_ids]
        else:
            hit = [x for x in res.explanations if x.field == lab["field"]]
        if hit:
            k["exact_field"] += 1
        if hit or any(lab["field"] in x.alternatives for x in res.explanations):
            k["field_flagged"] += 1
        extra_issues += len(res.explanations) - len(hit)
        if kind in NUMERIC_KINDS and hit:
            if any(x.pattern == kind for x in hit):
                k["cause"] += 1
            if any(x.expected == lab["original"] for x in hit):
                k["fix"] += 1
        elif kind not in NUMERIC_KINDS and hit:
            k["cause"] += 1
            k["fix"] += 1 if any(x.suggested_fix for x in hit) else 0

    seeded = sum(v["n"] for v in per_kind.values())
    pct = lambda a, b: round(100 * a / b, 1) if b else 0.0  # noqa: E731
    summary = {
        "filings": len(labels),
        "clean_filings": sum(1 for l in labels if l["kind"] == "CLEAN"),
        "seeded_filings": seeded,
        "detected_pct": pct(sum(v["detected"] for v in per_kind.values()), seeded),
        "exact_field_pct": pct(sum(v["exact_field"] for v in per_kind.values()), seeded),
        "field_flagged_pct": pct(sum(v["field_flagged"] for v in per_kind.values()), seeded),
        "correct_cause_pct": pct(sum(v["cause"] for v in per_kind.values()), seeded),
        "correct_fix_pct": pct(sum(v["fix"] for v in per_kind.values()), seeded),
        "false_alarms_on_clean": clean_issues,
        "extra_issues_on_seeded": extra_issues,
        "actionable_explanations_pct": pct(actionable, total_expl),
        "mean_ms_per_filing": round(1000 * statistics.mean(times), 1),
        "network_calls": network,
        "per_kind": {k: dict(per_kind[k]) for k in KINDS},
    }
    return summary


def to_markdown(s: dict) -> str:
    rows = "\n".join(
        f"| {k.replace('_', ' ').title()} | {v['n']} | {v['detected']} | {v['exact_field']} | {v['field_flagged']} "
        f"| {v['cause']} | {v['fix']} |"
        for k, v in s["per_kind"].items())
    return f"""# lulus.ai benchmark (synthetic)

{s['filings']} synthetic filings: {s['clean_filings']} clean and {s['seeded_filings']} with one seeded error each.
Generated by `tools/make_samples.py` (fixed seed, so anyone can reproduce it).

| Measure | Result |
| --- | --- |
| Seeded errors detected | **{s['detected_pct']}%** |
| Exact wrong field pinpointed as main suspect | **{s['exact_field_pct']}%** |
| Wrong field flagged (main or "also check") | {s['field_flagged_pct']}% |
| Correct likely cause | **{s['correct_cause_pct']}%** |
| Correct suggested fix | **{s['correct_fix_pct']}%** |
| False alarms on clean filings | **{s['false_alarms_on_clean']}** |
| Extra issues on seeded filings | {s['extra_issues_on_seeded']} |
| Explanations naming field, rule and fix | {s['actionable_explanations_pct']}% |
| Mean time per filing | {s['mean_ms_per_filing']} ms |
| Network calls during checks | **{s['network_calls']}** |

## By error type

| Error type | Filings | Detected | Exact field | Field flagged | Correct cause | Correct fix |
| --- | --- | --- | --- | --- | --- | --- |
{rows}

## Read this before quoting the numbers

* The filings are synthetic and generated by our own tool, so the layout is clean and every error is one of
  six known types. Real filings will be harder: scanned PDFs, unusual wording, several errors at once.
* The rule pack is a small sample modelled on MBRS-style checks, not SSM's official formula linkbase.
* Next: run the same filings through IRIS Instant and mTool, and add authorised real-world samples.
"""


if __name__ == "__main__":
    s = score(ROOT / "samples" / "benchmark")
    out = ROOT / "results"
    out.mkdir(exist_ok=True)
    (out / "benchmark.json").write_text(json.dumps(s, indent=2), encoding="utf-8")
    (out / "benchmark.md").write_text(to_markdown(s), encoding="utf-8")
    print(to_markdown(s))
